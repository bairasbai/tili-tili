/*
 * Хвост ревью 016 — фронт, F-RL-8-06: дашборд подрядчика открывался на
 * месяце по UTC, а не по местному календарю.
 *
 * Первого числа ночью подрядчик в Москве видел выручку и занятые даты ЗА
 * ПРОШЛЫЙ месяц, в Камчатке — почти весь первый день. Ошибка тихая: цифры
 * настоящие, просто не за тот месяц, и заметить её можно только сверив с
 * календарём.
 *
 * Про машинную зависимость честно: проверка различает старое и новое
 * поведение на любой машине с ПОЛОЖИТЕЛЬНЫМ смещением от UTC (эта — GMT+3,
 * сервер — в РФ). На машине в UTC оба варианта совпадают и тест пройдёт, не
 * увидев дефекта, — но ложно упасть он не может ни при каком поясе.
 */
import { describe, it, expect } from 'vitest'
import { currentMonth } from './utils'

describe('F-RL-8-06: месяц дашборда подрядчика — местный, не UTC', () => {
  it('полночь первого числа по местному времени — это уже новый месяц', () => {
    // `new Date(y, m, d, …)` строит по МЕСТНОМУ времени: 1 июня 00:30 у человека.
    expect(currentMonth(new Date(2027, 5, 1, 0, 30))).toBe('2027-06')
  })

  it('последний день месяца поздно вечером — ещё старый месяц', () => {
    expect(currentMonth(new Date(2027, 4, 31, 23, 45))).toBe('2027-05')
  })

  it('однозначная дата в середине месяца — без сюрпризов', () => {
    expect(currentMonth(new Date(2027, 11, 15, 12, 0))).toBe('2027-12')
  })

  it('без аргумента берёт текущий момент и совпадает с местным календарём', () => {
    const now = new Date()
    expect(currentMonth()).toBe(`${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`)
  })
})
