import { afterEach, beforeEach, expect, it, vi } from 'vitest'

const state = vi.hoisted(() => ({ complete: null as null | (() => void), current: true }))
vi.mock('@pdfme/generator', () => ({ generate: async () => { await new Promise<void>(resolve => { state.complete = resolve }); return new Uint8Array([37, 80, 68, 70]) } }))
vi.mock('./i18n', () => ({ appRoot: () => '/' }))
beforeEach(() => {
  vi.resetModules(); state.complete = null; state.current = true
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, arrayBuffer: async () => new ArrayBuffer(1) }))
  Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:pdf') })
  Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
})
afterEach(() => { vi.unstubAllGlobals(); vi.restoreAllMocks(); vi.useRealTimers() })

it.each(['denied', 'scope'] as const)('discards generated bytes when final access is %s', async reason => {
  const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined)
  const { downloadTextPdf } = await import('./localPdf')
  const check = vi.fn(async () => { if (reason === 'denied') throw new Error('403'); state.current = false })
  const pending = downloadTextPdf({ title: 'Test', body: 'Private text', filename: 'test.pdf', isCurrent: () => state.current, beforeDownload: check })
  // Attach rejection handler immediately to avoid an unhandled promise during the renderer wait.
  const outcome = pending.then(value => value, () => 'denied')
  await vi.waitFor(() => expect(state.complete).not.toBeNull())
  expect(check).not.toHaveBeenCalled()
  state.complete!()
  expect(await outcome).toBe(reason === 'denied' ? 'denied' : false)
  expect(check).toHaveBeenCalledOnce()
  expect(URL.createObjectURL).not.toHaveBeenCalled(); expect(click).not.toHaveBeenCalled()
})

it('downloads once after verification and releases its object URL', async () => {
  const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined)
  const { downloadTextPdf } = await import('./localPdf')
  const check = vi.fn(async () => undefined)
  const pending = downloadTextPdf({ title: 'Test', body: 'Text', filename: 'test.pdf', isCurrent: () => true, beforeDownload: check })
  await vi.waitFor(() => expect(state.complete).not.toBeNull())
  vi.useFakeTimers(); state.complete!()
  expect(await pending).toBe(true)
  expect(check).toHaveBeenCalledOnce(); expect(click).toHaveBeenCalledOnce()
  expect(document.querySelector('a[download]')).toBeNull()
  vi.runAllTimers(); expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:pdf')
})
