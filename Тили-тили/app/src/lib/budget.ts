import type { Slot } from './types'

/*
 * Обязательства пары по мозаике команды.
 *
 * Здесь остался только один расчёт — сумма того, о чём уже договорились.
 * Остальное считает сервер: строки бюджета, доли категорий и «потрачено»
 * приходят из `GET /weddings/{id}/budget`. Раньше рядом жил второй набор
 * правил на моках, и пара одновременно видела три разных ответа на вопрос
 * «сколько уже потрачено»: 455 000 ₽ на главной, 560 000 ₽ в «Нашем дне» и
 * 677 000 ₽ в бюджете (ERR-0012). Второй набор снесён вместе с моками.
 */

/** Слоты, по которым пара уже взяла обязательства: бронь и мягкая бронь. */
export const committedSlots = (slots: Slot[]): Slot[] =>
  slots.filter(s => (s.state === 'booked' || s.state === 'hold') && s.price)

/** Сумма обязательств в копейках. */
export const committedTotal = (slots: Slot[]): number =>
  committedSlots(slots).reduce((a, s) => a + (s.price ?? 0), 0)
