/*
 * Редакция юридических текстов, которые лежат В ЭТОЙ СБОРКЕ.
 *
 * Доказательство согласия по 152-ФЗ — это подпись под КОНКРЕТНЫМ текстом.
 * Сервер хранит номер редакции (`consents.policy_version`) и сверяет его при
 * фиксации согласия. Текст при этом живёт здесь, в приложении.
 *
 * До сих пор эти две вещи не были связаны ничем. Человек читал экран без
 * номера и без даты, а в базу ложилась редакция, о которой он не знал. Если
 * юрист заменит текст, а сборку не выкатят — или выкатят сборку, а редакцию
 * на сервере не поднимут, — в согласии окажется номер, под текстом которого
 * никто не подписывался. Восстановить, что именно человек видел, будет нечем:
 * старого текста нет ни в базе, ни в бандле.
 *
 * Поэтому сборка называет свою редакцию вслух. Экран входа сверяет её с
 * серверной и при расхождении не даёт поставить галочку: подписаться под
 * текстом, которого не видел, нельзя даже с согласия человека.
 *
 * Менять эту константу — вместе с текстами в `pages/Legal.tsx`, и только
 * вместе с `POLICY_VERSION` на сервере.
 */
export const LEGAL_TEXT_VERSION = '2026-09-02'

/**
 * Редакция для человека: «от 2 сентября 2026».
 *
 * Номер редакции — это дата, и показывать её кодом `2026-09-02` значит
 * заставлять читателя разбирать формат. Если однажды номер перестанет быть
 * датой, покажем его как есть.
 */
export function formatRedaction(version: string, lang: 'ru' | 'en'): string {
  const asDate = /^\d{4}-\d{2}-\d{2}$/.test(version) ? new Date(`${version}T00:00:00Z`) : null
  if (!asDate || Number.isNaN(asDate.getTime())) return version
  return asDate.toLocaleDateString(lang === 'en' ? 'en-GB' : 'ru-RU', {
    day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC',
  })
}
