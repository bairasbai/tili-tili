/**
 * Защиты переписки из §18.2 и §19.4.
 *
 * Обе — предупреждающие, а не запрещающие. Заблокировать сообщение значит
 * выгнать разговор в мессенджер, где нет ни договора, ни эскроу, ни следа
 * для разбирательства. Поэтому: чат не блокируем — информируем.
 */

/**
 * Слова, по которым сделка утекает мимо платформы (§18.2).
 *
 * Список из документа дословно. Расширять его наугад нельзя: ложное
 * срабатывание на «переведи на карту метро» стоит доверия, а поймать
 * все формулировки словарём всё равно не выйдет.
 */
const PAYOUT_TRIGGERS = ['номер карты', 'переведи на карту', 'переведите на карту', 'без договора']

export const PAYOUT_WARNING =
  'Переводы вне договора не защищены: деньги идут мимо эскроу, и вернуть их при отмене нечем. ' +
  'Договор формируется за две минуты в карточке сделки.'

/** Ссылка в тексте: в первом сообщении подрядчика это повод для модерации. */
const LINK = /(https?:\/\/|\bwww\.|\b[a-z0-9-]+\.(ru|com|net|org|io)\b)/i

export function looksLikePayoutBypass(text: string): boolean {
  const lower = text.toLowerCase()
  return PAYOUT_TRIGGERS.some((trigger) => lower.includes(trigger))
}

export function hasLink(text: string): boolean {
  return LINK.test(text)
}
