import { randomBytes } from 'node:crypto'

/**
 * UUID версии 7: первые 48 бит — время в миллисекундах, остальное случайно.
 *
 * План §2 требует сортируемые идентификаторы. Причина не в красоте: у v4
 * случайны все биты, и вставка в индекс попадает в случайную страницу B-дерева.
 * На таблице сообщений это превращается в постоянные разбиения страниц и
 * распухший индекс. У v7 соседние записи ложатся рядом.
 *
 * Побочный эффект, о котором надо знать: из v7 читается время создания.
 * Для идентификаторов сущностей это не тайна. Для того, что попадает
 * в публичную ссылку (токен гостя, код приглашения) v7 не годится —
 * там нужен полностью случайный секрет.
 *
 * Раскладка (RFC 9562): 48 бит времени, 4 бита версии (0111), 12 бит случайных,
 * 2 бита варианта (10), 62 бита случайных.
 */
export function uuidv7(now: number = Date.now()): string {
  const bytes = randomBytes(16)

  bytes[0] = (now / 2 ** 40) & 0xff
  bytes[1] = (now / 2 ** 32) & 0xff
  bytes[2] = (now / 2 ** 24) & 0xff
  bytes[3] = (now / 2 ** 16) & 0xff
  bytes[4] = (now / 2 ** 8) & 0xff
  bytes[5] = now & 0xff

  bytes[6] = (bytes[6]! & 0x0f) | 0x70 // версия 7
  bytes[8] = (bytes[8]! & 0x3f) | 0x80 // вариант RFC 4122

  const hex = bytes.toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

/** Время создания, зашитое в UUIDv7. Нужно кроне удаления просроченного. */
export function uuidv7Time(id: string): number {
  return Number.parseInt(id.replace(/-/g, '').slice(0, 12), 16)
}
