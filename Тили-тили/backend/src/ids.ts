import { randomBytes } from 'node:crypto'

/**
 * UUID версии 7: первые 48 бит — время в миллисекундах, остальное случайно.
 *
 * План §2 требует сортируемые идентификаторы. Причина не в красоте: у v4
 * случайны все биты, и вставка в индекс попадает в случайную страницу B-дерева.
 * На таблице сообщений это превращается в постоянные разбиения страниц и
 * распухший индекс. У v7 соседние записи ложатся рядом.
 *
 * Побочный эффект, о котором надо знать: из v7 читается время создания.
 * Для идентификаторов сущностей это не тайна. Для того, что попадает
 * в публичную ссылку (токен гостя, код приглашения) v7 не годится —
 * там нужен полностью случайный секрет.
 *
 * Раскладка (RFC 9562): 48 бит времени, 4 бита версии (0111), 12 бит случайных,
 * 2 бита варианта (10), 62 бита случайных.
 */
export function uuidv7(now: number = Date.now()): string {
  const bytes = randomBytes(16)

  bytes[0] = (now / 2 ** 40) & 0xff
  bytes[1] = (now / 2 ** 32) & 0xff
  bytes[2] = (now / 2 ** 24) & 0xff
  bytes[3] = (now / 2 ** 16) & 0xff
  bytes[4] = (now / 2 ** 8) & 0xff
  bytes[5] = now & 0xff

  bytes[6] = (bytes[6]! & 0x0f) | 0x70 // версия 7
  bytes[8] = (bytes[8]! & 0x3f) | 0x80 // вариант RFC 4122

  const hex = bytes.toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

/** Время создания, зашитое в UUIDv7. Нужно кроне удаления просроченного. */
export function uuidv7Time(id: string): number {
  return Number.parseInt(id.replace(/-/g, '').slice(0, 12), 16)
}

/**
 * Схема идентификатора — в адресе ИЛИ в теле запроса.
 *
 * Идентификатор уходит в запрос по колонке `uuid`. Непроверенная строка роняет
 * запрос ошибкой синтаксиса драйвера, и обработчик переводит её в 500
 * «внутренняя ошибка» с записью в лог как о падении сервера — вместо отказа
 * по формату (R-108, R-111).
 *
 * Проверка схемой, а не строкой в обработчике: схема срабатывает ДО него и
 * отвечает 422. Ответить 404 нельзя — путь контракта не должен отвечать 404
 * ни при каких параметрах (инвариант 10), такой ответ не отличить от
 * незарегистрированного адреса.
 *
 * Живёт здесь, а не копией в каждом файле маршрутов: копии одного шаблона
 * разъезжаются ровно так же, как разъехался список путей в `redact.ts`.
 *
 * Имя без слова PARAM намеренно. Первый свод искал только параметры АДРЕСА и
 * пропустил семь мест, где идентификатор приходит полем ТЕЛА: `busId` гостя,
 * `optionId` в голосовании за меню, `tableId` при рассадке, `vendorId` в брони
 * слота и в отзыве гостя. Дефект там тот же, а название `UUID_PARAM` уводило
 * от мысли применить шаблон к телу (ERR-0104).
 */
/*
 * Форма uuid — ровно та, что принимает `uuid_in` PostgreSQL: пять групп hex
 * через дефис. Прежний шаблон «36 знаков из [0-9a-f-]» пропускал 36 дефисов и
 * дефис не на границе группы, и `'…'::uuid` падал ошибкой 22P02 — 500 с
 * записью в журнал как об аварии (ERR-0221, R-111). Один шаблон на схему и на
 * проверки в обработчиках: копии разъезжаются (R-113).
 */
const UUID_PATTERN = '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
export const UUID_RE = new RegExp(UUID_PATTERN)
export const isUuid = (value: unknown): value is string => typeof value === 'string' && UUID_RE.test(value)
export const UUID_ID = { type: 'string', pattern: UUID_PATTERN } as const
