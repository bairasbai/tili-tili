import type { FastifyInstance } from 'fastify'

/**
 * Действующая редакция оферты и политики.
 *
 * Сервер сверяет присланный в `POST /users/me/consent` `policyVersion`
 * со своим и отказывает при расхождении — это доказательство по 152-ФЗ:
 * в базе должна лежать подпись под тем текстом, который человек видел.
 * Но взять эту редакцию клиенту было негде: в контракте она встречалась
 * ровно один раз, в теле запроса. Единственным способом узнать её было
 * прислать неверную и разобрать текст ошибки (ERR-0114).
 *
 * Цена отсутствия — не неудобство. Смена текста политики поднимает
 * `POLICY_VERSION`; развёрнутый фронт продолжает слать старую константу;
 * согласие перестаёт приниматься; а без согласия закрыто всё, потому что
 * `requireConsent` стоит на каждом маршруте кроме входа. Ни один новый
 * пользователь не завершает регистрацию, пока не выкатят фронт. То есть
 * юридическое действие владельца ломало вход в приложение.
 *
 * Без входа намеренно: галочка согласия стоит на экране ДО того, как
 * человек получил токены, — значит и редакцию он должен получить раньше.
 *
 * Сам текст живёт в приложении (`app/src/pages/Legal.tsx`). Сервер отдаёт
 * только редакцию, потому что только её он и проверяет: отдавать отсюда
 * текст значило бы завести второе место хранения того же документа.
 */
export async function legalRoutes(app: FastifyInstance): Promise<void> {
  app.get('/legal/policy', async () => ({ policyVersion: app.appConfig.policyVersion }))
}
