const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').trim()

/** Поиск городов по подстроке: точные совпадения в начале названия — первыми. */
export function searchCities(q: string, limit = 12): City[] {
  const n = norm(q)
  if (n.length < 2) return []
  const starts: City[] = []
  const contains: City[] = []
  for (const c of CITIES) {
    const name = norm(c.n)
    if (name.startsWith(n)) starts.push(c)
    else if (name.includes(n) || norm(c.r).startsWith(n) || (c.d && norm(c.d).includes(n))) contains.push(c)
  }
  return [...starts, ...contains].slice(0, limit)
}

